import {distance,makeOverlay,translate,rotate,moveControl,reverseDirection,pipeLength} from './spiral-overlay.mjs';
import {strict as assert} from 'node:assert';
const approx=(a,b,eps=1e-7)=>assert.ok(Math.abs(a-b)<eps,`${a} != ${b}`);
const poly=[{x:0,y:0},{x:6,y:0},{x:6,y:4},{x:0,y:4}];
const original=makeOverlay(poly,{turns:4});
const length=pipeLength(original);
const moved=translate(original,2,-3);
approx(pipeLength(moved),length);
for(let i=0;i<original.points.length;i++)approx(distance(original.points[i],original.points[(i+1)%original.points.length]),distance(moved.points[i],moved.points[(i+1)%moved.points.length]));
const rotated=rotate(original,Math.PI/2);
approx(pipeLength(rotated),length);
const full=rotate(original,Math.PI*2);
for(let i=0;i<original.points.length;i++)approx(distance(original.points[i],full.points[i]),0);
const reversed=reverseDirection(original);
approx(pipeLength(reversed),length);
assert.deepEqual(reversed.points[0],original.points.at(-1));
assert.deepEqual(reversed.points.at(-1),original.points[0]);
const distorted=moveControl(original,0,{x:-1,y:0});
assert.notEqual(pipeLength(distorted),length);
console.log('PASS: rigid translation/rotation preserve length; reverse changes traversal only; deformation changes length');
