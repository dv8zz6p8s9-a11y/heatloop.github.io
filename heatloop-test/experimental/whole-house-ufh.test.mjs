import {strict as assert} from 'node:assert';
import {configureRoom,coverageEstimate,layoutLoops,connectManifold,updateRoute,circuitSummary} from './whole-house-ufh.mjs';
const polygon=[{x:0,y:0},{x:8,y:0},{x:8,y:5},{x:0,y:5}];
const room=configureRoom({id:'salon',polygon},{spacing:.15,wallOffset:.1});
assert.equal(room.area,40);
assert.equal(room.layout,null);
const estimate=coverageEstimate(room);
assert.ok(estimate.estimatedPipeLength>0);
const laid=layoutLoops(room,{feedAllowance:10});
assert.ok(laid.layout.count>=2);
assert.equal(room.layout,null,'configure stage must not split room');
assert.throws(()=>layoutLoops(room,{maxLength:120}),/zgody/);
assert.ok(layoutLoops(room,{maxLength:120,allowExtended:true,approvedExtended:true}).layout.count>0);
const wall=[{a:{x:3,y:-1},b:{x:3,y:1}}];
const route=connectManifold({x:6,y:0},{x:0,y:0},wall);
assert.equal(route.wallCollisions.length,1);
const detour=updateRoute(route,'insert',1,{x:0,y:2},wall);
const safe=updateRoute(detour,'insert',2,{x:6,y:2},wall);
assert.equal(safe.wallCollisions.length,0);
const sum=circuitSummary({pipeLength:75,supply:safe,returnRoute:safe});
assert.ok(sum.total>75);
assert.equal(sum.hasCollisions,false);
console.log('Whole-house planning tests passed');
